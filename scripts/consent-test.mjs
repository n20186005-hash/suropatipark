import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const script = readFileSync('src/layouts/BaseLayout.astro', 'utf8').match(/<script is:inline>([\s\S]*?)<\/script>/)[1];
const banner = { hidden: true, dataset: { storageError: 'not saved', saved: 'saved' } };
const output = { textContent: '', dataset: {} };
const buttons = ['analytics', 'essential'].map(cookie => ({ dataset: { cookie }, events: {}, addEventListener(event, fn) { this.events[event] = fn; } }));
const loaded = [];
const context = { window: {}, localStorage: { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } }, document: { querySelector: key => key === '#cookie-banner' ? banner : output, querySelectorAll: key => key === '[data-cookie]' ? buttons : [output], createElement: () => ({}), head: { appendChild: s => loaded.push(s) } } };
vm.runInNewContext(script, context);
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 0);
assert.equal(banner.hidden, false);
buttons[0].events.click();
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], false);
assert.equal(loaded.length, 1);
assert.equal(output.textContent, 'not saved');
buttons[1].events.click();
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 1);
assert.equal(output.textContent, 'not saved');
console.log('Consent: blocked storage, explicit current-page grant and immediate refusal passed.');
